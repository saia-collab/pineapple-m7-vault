def prompt(question: str, default: str | None = None) -> str:
    """Tiny input wrapper that surfaces the default in brackets."""
    suffix = f" [{default}]" if default else ""
    answer = input(f"{question}{suffix}: ").strip()
    return answer or (default or "")


def pick(question: str, options: list[str], default: str) -> str:
    """Numbered-choice picker. Returns the selected option string."""
    print(f"\n{question}")
    for i, opt in enumerate(options, 1):
        marker = "*" if opt == default else " "
        print(f"  {marker} {i}. {opt}")
    raw = input(f"Pick 1-{len(options)} [default {default}]: ").strip()
    if not raw:
        return default
    try:
        return options[int(raw) - 1]
    except (ValueError, IndexError):
        print(f"  → invalid pick, using default: {default}")
        return default


def write_env_key(env_path: Path, key_name: str, key_value: str) -> None:
    """Append or replace a KEY=value line in a .env file. Creates the file if missing."""
    env_path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    if env_path.exists():
        with env_path.open("r") as f:
            lines = [line for line in f.read().splitlines() if not line.startswith(f"{key_name}=")]
    lines.append(f"{key_name}={key_value}")
    with env_path.open("w") as f:
        f.write("\n".join(lines) + "\n")
    # Lock down — keys are secrets
    env_path.chmod(0o600)


